import React from 'react'
import { describe, it, expect, vi, afterEach } from 'vitest'
import { render, screen } from '@testing-library/react'
import apiClient from '@/lib/api/client'
import { discoveryApi } from '@/lib/api/discovery'
import { brandByline } from '@/lib/brand-name'
import { BrandByline } from '@/components/features/brand-byline'

/**
 * NEW-269 (owner 2026-11-18, R-112): the website's gym page shows "by <brand>" under the gym name, as the
 * app does (rule 9: the website copies mobile). The brand is tenants.business_name, which the gym detail
 * answer already carries as gym.tenant.businessName. A brand generated by app builds up to 25
 * ("<full name>'s Gym Business") or one equal to the gym name is not shown.
 */
afterEach(() => vi.restoreAllMocks())

describe('brandByline (same rule as the app)', () => {
  it('a typed brand that is not the gym name', () => {
    expect(brandByline('Iron Works', 'Iron Works Saddar')).toBe('by Iron Works')
    expect(brandByline('Iron Works', 'iron works')).toBeNull()
    expect(brandByline("Amir Khan's Gym Business", 'Iron Den')).toBeNull()
    expect(brandByline('', 'Iron Den')).toBeNull()
    expect(brandByline(undefined, 'Iron Den')).toBeNull()
  })
})

describe('gym detail', () => {
  it('getGym keeps the brand from gym.tenant.businessName', async () => {
    vi.spyOn(apiClient, 'get').mockResolvedValue({
      data: { success: true, data: { gym: { id: 'g1', title: 'Iron Works Saddar', tenant: { id: 't1', businessName: 'Iron Works' } } } },
    } as never)
    const res = await discoveryApi.getGym('g1')
    expect(res.data.brandName).toBe('Iron Works')
  })

  it('the page line shows "by <brand>", and nothing for a generated name', () => {
    const { rerender } = render(<BrandByline brand="Iron Works" gymName="Iron Works Saddar" />)
    expect(screen.getByText('by Iron Works')).toBeInTheDocument()
    rerender(<BrandByline brand="Amir Khan's Gym Business" gymName="Iron Den" />)
    expect(screen.queryByText(/^by /)).toBeNull()
  })

  it('the gym page uses it under the title', async () => {
    const fs = await import('node:fs')
    const src = fs.readFileSync('src/app/(public)/gyms/[id]/page.tsx', 'utf8')
    expect(src).toContain('<BrandByline brand={gym.brandName} gymName={gym.name}')
  })
})
